/**
 * BRAND REEL — the Remotion composition, and the props contract that drives it.
 *
 * The source below is submitted VERBATIM to the platform render service by the
 * pv-render-composition server function, so it is a plain string: no backticks
 * inside it, no TypeScript annotations, nothing that needs a build step beyond
 * the service's own TSX compile. Everything variable arrives through `props`.
 *
 * HOW IT IS PUT TOGETHER
 *   theme.*      colour, type and spacing tokens — the CLIENT's brand, resolved
 *                once in the app and passed in; the composition never hardcodes
 *                a palette
 *   TIMING       every value derives from useCurrentFrame() / useVideoConfig()
 *                and the frame constants in props. There are no magic frame
 *                numbers and no unseeded randomness — the same props always
 *                render the same frames
 *   COMPONENTS   Backdrop, UIFrame, Kinetic, BodyLine, CaptionBar, SceneChrome,
 *                CtaPlate and SceneTransition are reusable across every scene
 *   MOTION       transform + opacity only. No width/height/top/left animation,
 *                no filter animation, nothing that forces layout during a render
 *
 * ASSETS: the render service has no Remotion public/ directory, so staticFile()
 * has nothing to resolve. Every asset here is an absolute https URL on platform
 * storage, loaded through Remotion's <Img> / <Audio>, which hold the frame until
 * the asset has decoded — that is the reliable preload on this pipeline.
 *
 * GEOMETRY: the service is locked to 30fps 1920x1080. A 9:16 reel renders a
 * centred 608px vertical stage inside that canvas, the same convention the
 * Remotion Studio tab uses.
 */
import {
  BrandObject, BrandTheme, SceneVisual, ScriptVariant, SceneMockup, TransitionKind,
  REEL_FPS, brandTheme, emptySceneVisual,
} from './types';

/** Cross-fade / slide overlap between consecutive scenes, per transition. */
export const TRANSITION_FRAMES: Record<TransitionKind, number> = {
  crossfade: 18,
  slide: 14,
  wipe: 14,
  cut: 0,
};

export interface ReelSceneProps {
  sceneNumber: number;
  durationFrames: number;
  headline: string;
  bodyText: string;
  caption: string;
  /** Only read when visual.kind is 'product-ui'. */
  imageUrl: string;
  /** The shape this scene is DRAWN as — see SceneGraphic in the source below. */
  visual: SceneVisual;
  /** Seconds into the reel this scene's narration begins — the VO marker. */
  voiceoverAtSeconds: number;
}

export interface ReelProps {
  productName: string;
  tagline: string;
  ctaLabel: string;
  logoUrl: string;
  heroImageUrl: string;
  host: string;
  accent: string;
  accentStrong: string;
  onAccent: string;
  bgDeep: string;
  bgLift: string;
  fontFamily: string;
  aspect: '16:9' | '9:16';
  transition: TransitionKind;
  transitionFrames: number;
  captionsEnabled: boolean;
  scenes: ReelSceneProps[];
  musicUrl: string;
  musicVolume: number;
  voiceoverUrl: string;
  [key: string]: unknown;
}

/**
 * Total length once the per-scene overlaps are folded in. The render call and
 * the composition must agree on this number or the last scene is clipped.
 */
export function totalReelFrames(sceneFrames: number[], overlap: number): number {
  const sum = sceneFrames.reduce((a, b) => a + b, 0);
  const merged = Math.max(0, sceneFrames.length - 1) * overlap;
  return Math.max(REEL_FPS, sum - merged);
}

/** Darken a hex toward the page canvas without importing the theme helpers. */
function deepen(hex: string, amount: number): string {
  const h = /^#[0-9a-fA-F]{6}$/.test(hex) ? hex.slice(1) : '0b0f18';
  const ch = (i: number) => Math.round(parseInt(h.slice(i, i + 2), 16) * (1 - amount));
  const hx = (n: number) => Math.max(0, Math.min(255, n)).toString(16).padStart(2, '0');
  return `#${hx(ch(0))}${hx(ch(2))}${hx(ch(4))}`;
}

/**
 * Per-scene visual overrides. Brand Reel does not pass these — it generates a
 * mockup for every scene. Remotion Studio does: it spreads the stills it read
 * off the customer's own site across the scenes.
 */
export interface ReelVisualOverrides {
  /** sceneNumber → still image URL, used instead of the mockup lookup. */
  images?: Record<number, string>;
}

/**
 * THERE IS NO VIDEO OVERRIDE, and that is deliberate. The platform render
 * service rejects any composition containing <OffthreadVideo> at bundle-
 * verification time — "requires a string for `src`, but got undefined" — even
 * with a hardcoded, valid, publicly-fetchable src and no props involved.
 * <Video> fails identically because the service's Remotion bundle aliases it
 * to the same tag. Verified against the live service on 27 Sep 2026 across
 * three isolating renders. Footage scraped off a customer's page is therefore
 * surfaced in the UI as reference material and never composited into a render.
 */

/** Build the render props from the confirmed brand, variant and mockups. */
export function buildReelProps(
  brand: BrandObject,
  variant: ScriptVariant,
  mockups: SceneMockup[],
  options: { captionsEnabled: boolean; musicUrl: string; voiceoverUrl: string },
  overrides: ReelVisualOverrides = {},
): { props: ReelProps; durationInFrames: number; theme: BrandTheme } {
  const theme = brandTheme(brand);
  const overlap = TRANSITION_FRAMES[variant.composition.transition] ?? TRANSITION_FRAMES.crossfade;

  let elapsedFrames = 0;
  const scenes: ReelSceneProps[] = variant.scenes.map((scene, index) => {
    const durationFrames = Math.max(REEL_FPS, Math.round(scene.durationSeconds * REEL_FPS));
    const startFrame = Math.max(0, elapsedFrames - index * overlap);
    elapsedFrames += durationFrames;
    const mockup = mockups.find((m) => m.sceneNumber === scene.sceneNumber);
    const overrideImage = overrides.images?.[scene.sceneNumber] || '';
    return {
      sceneNumber: scene.sceneNumber,
      durationFrames,
      headline: scene.headline,
      bodyText: scene.bodyText,
      caption: scene.voiceover,
      imageUrl: overrideImage
        || (mockup?.status === 'ready' ? mockup.imageUrl : brand.heroImageUrl || ''),
      // A product-ui scene with no picture to show would draw the generic UI
      // skeleton under a "this is our product" headline, which reads as a lie.
      visual: scene.visual && scene.visual.kind === 'product-ui'
        && !(overrideImage || mockup?.imageUrl || brand.heroImageUrl)
        ? emptySceneVisual('kinetic')
        : scene.visual || emptySceneVisual('kinetic'),
      voiceoverAtSeconds: Math.round((startFrame / REEL_FPS) * 10) / 10,
    };
  });

  const durationInFrames = totalReelFrames(scenes.map((s) => s.durationFrames), overlap);

  return {
    theme,
    durationInFrames,
    props: {
      productName: brand.name,
      tagline: brand.tagline,
      ctaLabel: brand.cta,
      logoUrl: brand.logoUrl,
      heroImageUrl: brand.heroImageUrl,
      host: brand.url,
      accent: theme.primary,
      accentStrong: theme.primaryStrong,
      onAccent: theme.onPrimary,
      bgDeep: deepen(theme.secondary, 0.55),
      bgLift: deepen(theme.secondary, 0.2),
      fontFamily: theme.fontFamily,
      aspect: variant.composition.aspect,
      transition: variant.composition.transition,
      transitionFrames: overlap,
      captionsEnabled: options.captionsEnabled,
      scenes,
      musicUrl: options.musicUrl,
      musicVolume: options.voiceoverUrl ? 0.16 : 0.28,
      voiceoverUrl: options.voiceoverUrl,
    },
  };
}

